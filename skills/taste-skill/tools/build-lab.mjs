// Classic scripts open from file URLs. Bundle the same ES modules used by the CLIs.
import fs from 'node:fs';
const file=p=>new URL(p,import.meta.url);
// The dealer owns these shapes. Keep CLI and file-URL previews on those exact outlines.
const system=fs.readFileSync(file('../assets/system.css'),'utf8');
const marks={};
for(const match of system.matchAll(/\.mark\[data-mark="([^"]+)"\]\s*\{\s*--mark:\s*url\("data:image\/svg\+xml,([^"]+)"\)/g)){
  const markup=decodeURIComponent(match[2]).match(/<svg[^>]*>([\s\S]+)<\/svg>/);
  if(markup)marks[match[1]]=markup[1];
}
if(!marks.dots||!marks.ring)throw Error('Could not read dealer marks.');
fs.writeFileSync(file('lib/share-marks.js'),'// Generated from assets/system.css by build-lab.mjs.\nexport const marks = '+JSON.stringify(marks,null,2)+';\n');
const all=['common','colour','tile','grain','show-svg','show','gradient','contours','pattern','shape','shadow','surface','divider','palette','device','grade','chart','frame','scribble','object','typescale','share-marks','share'];
let bundle='/* Generated by build-lab.mjs. Edit the modules in lib. */\nconst toolbox = {};\n';
for(const name of all){
 let source=fs.readFileSync(file('lib/'+name+'.js'),'utf8').replace(/^import \{([^}]+)\} from '.\/([^']+)\.js';/gm,(_,items,dep)=>'const {'+items.replace(/ as /g,':')+'}=toolbox['+JSON.stringify(dep)+'];');
 const exports=[...source.matchAll(/export (?:const|function) (\w+)/g)].map(m=>m[1]);
 if(!['common','tile','colour','contours','show','show-svg','share-marks'].includes(name))exports.push('uses','knobs');
 source=source.replace(/export (const|function)/g,'$1');
 bundle+='toolbox['+JSON.stringify(name)+']=(()=>{\n'+source+'\nreturn {'+[...new Set(exports)].join(',')+'};})();\n';
}
const palettes=JSON.parse(fs.readFileSync(file('../library/palettes.json'))).map(({id,name,bg,ink,accent,muted,surface})=>({id,name,bg,ink,accent,muted,surface}));
fs.writeFileSync(file('lab-bundle.js'),bundle+'const palettes='+JSON.stringify(palettes)+';\n');
